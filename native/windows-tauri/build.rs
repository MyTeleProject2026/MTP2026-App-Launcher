use std::{env, fs, path::PathBuf};

fn ensure_windows_icon() {
    let manifest_dir = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is required"));
    let icon_path = manifest_dir.join("icons").join("icon.ico");

    if icon_path.is_file() {
        return;
    }

    fs::create_dir_all(icon_path.parent().expect("icon directory must exist"))
        .expect("failed to create Tauri icon directory");

    // Minimal valid 1x1 32-bit ICO used as a deterministic build fallback.
    // If a project-provided icon.ico exists, it is preserved unchanged.
    const ICO: &[u8] = &[
        0x00, 0x00, 0x01, 0x00, 0x01, 0x00,
        0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00,
        0x30, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00,
        0x28, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x02, 0x00, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0x00, 0x00,
        0x00, 0x00,
    ];

    fs::write(&icon_path, ICO).expect("failed to create fallback Tauri Windows icon");
    println!("cargo:rerun-if-changed={}", icon_path.display());
}

fn main() {
    ensure_windows_icon();
    tauri_build::build();
}
